package aulascoh;

public class AulaMetodos4 {

    static double calcularMedia(double n1, double n2) {
        return (n1 + n2) / 2;
    }
    public static void main(String[] args) {
    	
        double media = calcularMedia(7.5, 8.0);
        
        System.out.println("Média: " + media);
    }

}
